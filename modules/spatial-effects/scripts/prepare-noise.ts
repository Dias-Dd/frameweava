import {readFile,writeFile} from 'node:fs/promises';
import {join,resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),vendor=join(root,'vendor/fastnoise-lite');
const source=JSON.parse(await readFile(join(vendor,'SOURCE.json'),'utf8'));
for(const f of source.files)if(createHash('sha256').update(await readFile(join(vendor,f.local))).digest('hex')!==f.sha256)throw Error('Unreviewed FastNoiseLite bytes: '+f.local);
const original=await readFile(join(vendor,'FastNoiseLite.glsl'),'utf8');let arrays=0;
// Mechanical GLSL ES3 syntax adaptation only. Preserve constants/order and unmodified original.
const shader=original.replace(/const float (\w+)\[\]\s*=\s*\{([\s\S]*?)\};/g,(_all,name,body)=>{arrays++;return `const float ${name}[] = float[](${body});`;}).replace(/\b((?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?)f\b/g,'$1');
if(arrays!==4)throw Error('Unexpected upstream array syntax count: '+arrays);
await writeFile(join(root,'src/noise-glsl.ts'),'// Generated by scripts/prepare-noise.ts. Byte-preserved MIT source in vendor/fastnoise-lite.\nexport const noiseGlsl='+JSON.stringify(shader)+';\n');
console.log(JSON.stringify({source:source.commit,arrayConstructors:arrays,sha256:createHash('sha256').update(shader).digest('hex')}));
